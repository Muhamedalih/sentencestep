import type { Metadata } from "next";
import Link from "next/link";

import { FishAudioVoiceForm } from "@/components/admin/fish-audio-voice-form";
import { NotConfiguredNotice } from "@/components/admin/not-configured-notice";
import { WordAudioDashboardRow } from "@/components/admin/word-audio-dashboard-row";
import { Button } from "@/components/ui/button";
import { Card, CardContent } from "@/components/ui/card";
import { getFishAudioVoices } from "@/lib/admin/fish-audio-queries";
import { getVoices } from "@/lib/admin/voices-queries";
import { listWordAudioDashboardRows } from "@/lib/admin/word-audio-queries";
import { isSupabaseConfigured } from "@/lib/supabase/config";
import { isWordListProvider } from "@/lib/voice/content-provider-map";

export const metadata: Metadata = { title: "Word Audio Status" };

const LEVEL_LABELS: Record<number, string> = {
  1: "Beginner",
  2: "Intermediate",
  3: "Advanced",
};

/** Word Lists narration dashboard — mirrors /admin/voice/content (Story audio status): one row per word group with its audio completeness, a per-group voice picker and a Generate button. Adds the Fish Audio browser on top so a voice can be found, heard, added and assigned from this one page. */
export default async function AdminWordAudioStatusPage() {
  if (!isSupabaseConfigured()) return <NotConfiguredNotice />;

  const [{ rows, defaultVoiceId }, allVoices, fishVoices] = await Promise.all([
    listWordAudioDashboardRows(),
    getVoices(),
    getFishAudioVoices(),
  ]);
  // Only voices Word Lists can actually generate with — see
  // content-provider-map.ts's WORD_LIST_PROVIDERS.
  const pickableVoices = allVoices.filter((voice) => isWordListProvider(voice.source));
  const defaultVoiceName =
    allVoices.find((voice) => voice.id === defaultVoiceId)?.name ?? defaultVoiceId;

  const levels = [...new Set(rows.map((row) => row.level))].sort((a, b) => a - b);

  return (
    <div className="flex flex-col gap-6">
      <div className="flex items-start justify-between gap-4">
        <div>
          <h1 className="text-3xl font-semibold tracking-tight">Word audio status</h1>
          <p className="text-muted-foreground mt-1">
            Pronunciation audio for every Word List group. Each row&apos;s voice picker sets that
            group&apos;s narration voice — Edge-TTS (free) or Fish Audio (free) — and starts
            generating it straight away; learners keep hearing the current voice for that group
            until every word is ready in the new one, then switch over together. Find and add Fish
            voices in the card below. &quot;Default voice&quot; follows the Word Lists default set
            on the main Voice page. Existing audio is never deleted or regenerated by changing a
            voice.
          </p>
        </div>
        <Button asChild variant="secondary">
          <Link href="/admin/voice">Voice settings</Link>
        </Button>
      </div>

      <FishAudioVoiceForm voices={fishVoices} />

      {levels.length === 0 && (
        <p className="text-muted-foreground text-center text-sm">No word groups yet.</p>
      )}
      {levels.map((level) => {
        const levelRows = rows.filter((row) => row.level === level);
        return (
          <div key={level}>
            <h2 className="mb-2 text-lg font-semibold">
              {LEVEL_LABELS[level] ?? `Level ${level}`} ({levelRows.length})
            </h2>
            <Card>
              <CardContent className="flex flex-col divide-y p-0">
                {levelRows.map((row) => (
                  <WordAudioDashboardRow
                    key={row.id}
                    row={row}
                    voices={pickableVoices}
                    defaultVoiceName={defaultVoiceName}
                  />
                ))}
              </CardContent>
            </Card>
          </div>
        );
      })}
    </div>
  );
}
